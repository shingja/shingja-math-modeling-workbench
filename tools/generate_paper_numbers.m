%% Self-test
function self_test()
%% Build dummy results.json, generate auto_numbers.tex, verify contents.
tmp = fullfile(tempdir, 'test_paper_numbers.json');

% === Test 1: key_results array with mixed value types ===
res.key_results = struct( ...
    'name',  {{'方案A得分', '方案B得分', '最优方案', '1号方案成本', 'R_squared_score'}}, ...
    'value', {{0.8234, 0.6175, 1, 1456.78, 0.03142}});
res.goodness = 0.9512;
res.objective_value = 3.14159265e-5;

fid = fopen(tmp, 'w');
fprintf(fid, '%s', jsonencode(res));
fclose(fid);

out1 = fullfile(tempdir, 'auto_numbers.tex');
generate_paper_numbers(tmp, out1);

content = fileread(out1);

% Verify header
assert(contains(content, '% AUTO-GENERATED'), ...
    'Output should contain AUTO-GENERATED header');
assert(contains(content, 'DO NOT EDIT'), ...
    'Output should contain DO NOT EDIT warning');

% Verify key_results entries
assert(contains(content, '\resultA'), ...
    'Should contain sanitized name for 方案A得分');
assert(contains(content, '\resultB'), ...
    'Should contain sanitized name for 方案B得分');
assert(contains(content, '0.8234'), ...
    'Should contain numerical value 0.8234');
assert(contains(content, '0.6175'), ...
    'Should contain numerical value 0.6175');

% Verify digit-starting name gets 'n' prefix
assert(contains(content, '\resultn1'), ...
    '1号方案成本 → \resultn1 (prepend n for digit start)');

% Verify scalar fields
assert(contains(content, '\resultgoodness'), ...
    'Should contain scalar field goodness');
assert(contains(content, '\resultobjective_value'), ...
    'Should contain scalar field objective_value');

% Count newcommand entries: 5 key_results + 2 scalars = 7
lines = strsplit(strtrim(content), newline);
cmd_count = sum(contains(lines, '\newcommand'));
assert(cmd_count >= 7, ...
    sprintf('Expected >=7 newcommand entries, got %d', cmd_count));

% === Test 2: empty key_results, only scalar fields ===
