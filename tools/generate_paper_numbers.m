function generate_paper_numbers(results_json_path, output_tex_path)
%% GENERATE_PAPER_NUMBERS Extract numerical results from JSON, output LaTeX newcommands. v3.0.0.
%  Reads results/results.json → generates auto_numbers.tex
%  Each key_result becomes: \newcommand{\result<SanitizedName>}{<value>}
%  Paper uses: \resultQoneScore → 0.8234
%
%  Sanitization:
%    - Strips all non-[a-zA-Z0-9_] characters from names
%    - Prepends 'n' to names starting with a digit
%
%  Formatting (4 significant digits heuristic):
%    - Large or tiny values   → % .4e  (scientific)
%    - Sub-unity values       → % .4f  (fixed decimal)
%    - Otherwise              → % .4g  (general)
%
%  Example:
%    results.key_results(1).name  = '方案A得分'
%    results.key_results(1).value = 0.8234
%    → \newcommand{\resultA}{0.8234}
arguments
    results_json_path (1,:) char
    output_tex_path  (1,:) char = ''
end

if isempty(output_tex_path)
    [dir, ~] = fileparts(results_json_path);
    output_tex_path = fullfile(dir, 'auto_numbers.tex');
end

% Read results JSON
results = jsondecode(fileread(results_json_path));

% Build newcommand entries
lines = {};
lines{end+1} = '% AUTO-GENERATED by generate_paper_numbers.m — DO NOT EDIT';
lines{end+1} = '% Source: results/results.json';
lines{end+1} = '';

if isfield(results, 'key_results') && ~isempty(results.key_results)
    for i = 1:numel(results.key_results)
        kr = results.key_results(i);

        % Sanitize name: remove spaces, special chars
        cmd_name = regexprep(kr.name, '[^a-zA-Z0-9_]', '');
        % Cannot start with digit → prepend 'n'
        cmd_name = regexprep(cmd_name, '^([0-9])', 'n$1');

        % Format value: 4 significant digits
        if isfield(kr, 'value') && isnumeric(kr.value)
            val = kr.value;
            if abs(val) >= 1000 || (abs(val) < 0.001 && abs(val) > 0)
                line = sprintf('\\newcommand{\\result%s}{%.4e}', cmd_name, val);
            elseif abs(val) < 1 && abs(val) > 0
                line = sprintf('\\newcommand{\\result%s}{%.4f}', cmd_name, val);
            else
                line = sprintf('\\newcommand{\\result%s}{%.4g}', cmd_name, val);
            end
            lines{end+1} = line;
        end
    end
end

% Also handle scalar fields directly on results struct
scalar_fields = {'goodness','r_squared','calibration_score', ...
                 'objective_value','optimal_cost'};
for i = 1:numel(scalar_fields)
    fn = scalar_fields{i};
    if isfield(results, fn) && isnumeric(results.(fn))
        cmd_name = regexprep(fn, '[^a-zA-Z0-9_]', '');
        val = results.(fn);
        if abs(val) >= 1000 || (abs(val) < 0.001 && abs(val) > 0)
            line = sprintf('\\newcommand{\\result%s}{%.4e}', cmd_name, val);
        elseif abs(val) < 1 && abs(val) > 0
            line = sprintf('\\newcommand{\\result%s}{%.4f}', cmd_name, val);
        else
            line = sprintf('\\newcommand{\\result%s}{%.4g}', cmd_name, val);
        end
        lines{end+1} = line;
    end
end

% Write file
fid = fopen(output_tex_path, 'w');
for i = 1:numel(lines)
    fprintf(fid, '%s\n', lines{i});
end
fclose(fid);
end

